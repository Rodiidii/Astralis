import threading
from functools import partial
from playwright.sync_api import sync_playwright, expect
from voyage_browser import ROOT, Quiet, Server


def main():
    server=Server(('127.0.0.1',0),partial(Quiet,directory=str(ROOT)))
    threading.Thread(target=server.serve_forever,daemon=True).start()
    base=f'http://127.0.0.1:{server.server_port}'
    try:
        with sync_playwright() as p:
            browser=p.chromium.launch()
            page=browser.new_page()
            errors=[]
            page.on('pageerror',lambda error:errors.append(str(error)))
            page.route('**/*',lambda route:route.continue_() if route.request.url.startswith(base) else route.abort())
            page.goto(base+'/tests/fixtures/arcade-tetris-settings.html',wait_until='domcontentloaded')
            passive_preview=page.locator('[data-arcade-passive-preview]')
            expect(passive_preview).to_contain_text('Venti')
            expect(passive_preview).to_contain_text('Souffle de Barbatos')
            zhongli=page.locator('[data-arcade-companion-choice="1"]')
            zhongli.focus()
            expect(passive_preview).to_contain_text('Pilier de pierre')
            expect(zhongli).to_have_attribute('aria-pressed','false')
            zhongli.click()
            expect(passive_preview).to_contain_text('Zhongli')
            expect(zhongli).to_have_attribute('aria-pressed','true')
            page.locator('[data-contract-play="memory"]').click()
            expect(page.locator('[data-arcade-mode="memory"]')).to_have_attribute('aria-selected','true')
            expect(page.locator('[data-arcade-view="memory"]')).to_be_visible()
            page.locator('[data-contract-play="boss"]').click()
            expect(page.locator('[data-arcade-mode="boss"]')).to_have_attribute('aria-selected','true')
            expect(page.locator('[data-arcade-view="boss"]')).to_be_visible()
            page.locator('[data-arcade-mode="tetris"]').click()
            expect(page.locator('[data-grid-preview-size]')).to_have_text('10 × 20')
            page.evaluate("""()=>{const buttons=Array.from({length:16},()=>({pressed:false,value:0}));window.__fakePadButtons=buttons;Object.defineProperty(navigator,'getGamepads',{configurable:true,value:()=>[{connected:true,index:0,id:'Manette de test',mapping:'standard',axes:[0,0],buttons}]});window.dispatchEvent(new Event('gamepadconnected'))}""")
            expect(page.locator('[data-gamepad-connection]')).to_have_text('Connectée')
            page.evaluate("window.__fakePadButtons[0].pressed=true")
            expect(page.locator('[data-gamepad-last-input]')).to_have_text('Dernière commande : Tourner')
            page.evaluate("window.__fakePadButtons[0].pressed=false")
            page.evaluate("window.__fakePadButtons[14].pressed=true")
            expect(page.locator('[data-gamepad-last-input]')).to_have_text('Dernière commande : Gauche')
            page.evaluate("window.__fakePadButtons[14].pressed=false")
            page.locator('.arcade-settings>summary').click()
            page.locator('[data-tetris-preset="calm"]').click()
            expect(page.locator('[data-grid-preview-size]')).to_have_text('8 × 16')
            expect(page.locator('[data-tetris-preset="calm"]')).to_have_attribute('aria-pressed','true')
            saved=page.evaluate("JSON.parse(localStorage.getItem('astralis:arcade:tetris-settings:v1'))")
            assert (saved['cols'],saved['rows'],saved['speed'],saved['special'],saved['grid'])==(8,16,'relaxed',False,False), saved
            page.locator('[data-tetris-preset="challenge"]').click()
            expect(page.locator('[data-grid-preview-size]')).to_have_text('12 × 24')
            expect(page.locator('[data-tetris-preset="challenge"]')).to_have_attribute('aria-pressed','true')
            saved=page.evaluate("JSON.parse(localStorage.getItem('astralis:arcade:tetris-settings:v1'))")
            assert (saved['cols'],saved['rows'],saved['speed'],saved['special'],saved['ghost'],saved['grid'])==(12,24,'rapid',True,False,True), saved
            page.locator('[data-arcade-audio]').click()
            expect(page.locator('[data-arcade-audio]')).to_have_attribute('aria-pressed','true')
            assert page.evaluate("localStorage.getItem('astralis:arcade:sfx-enabled:v1')")=='true'
            volume=page.locator('[data-arcade-volume]')
            volume.evaluate("el=>{el.value='35';el.dispatchEvent(new Event('input',{bubbles:true}))}")
            expect(page.locator('[data-arcade-volume-value]')).to_have_text('35 %')
            assert page.evaluate("localStorage.getItem('astralis:arcade:sfx-volume:v1')")==str(0.35)
            page.reload()
            expect(page.locator('[data-arcade-audio]')).to_have_attribute('aria-pressed','true')
            expect(page.locator('[data-arcade-volume]')).to_have_value('35')
            page.set_viewport_size({'width':390,'height':844})
            expect(page.locator('[data-arcade-volume]')).to_be_visible()
            page.locator('[data-arcade-music]').click()
            music_volume=page.locator('[data-arcade-music-volume]')
            expect(music_volume).to_be_visible()
            music_volume.evaluate("el=>{el.value='40';el.dispatchEvent(new Event('input',{bubbles:true}))}")
            expect(page.locator('[data-arcade-music-volume-value]')).to_have_text('40 %')
            assert page.evaluate("localStorage.getItem('astralis:arcade:music-volume:v1')")==str(0.4)
            assert page.locator('body').evaluate('node=>node.scrollWidth<=innerWidth+1')
            page.reload()
            page.set_viewport_size({'width':390,'height':844})
            page.locator('[data-arcade-music]').click()
            expect(page.locator('[data-arcade-music-volume]')).to_have_value('40')
            assert abs(page.locator('[data-arcade-audio-player]').evaluate('el=>el.volume')-.4)<.001
            page.locator('[data-arcade-music-close]').click()
            page.locator('[data-arcade-audio]').click()
            expect(page.locator('[data-arcade-audio]')).to_have_attribute('aria-pressed','false')
            assert page.evaluate("localStorage.getItem('astralis:arcade:sfx-enabled:v1')")=='false'
            page.locator('.arcade-settings>summary').click()
            page.locator('[data-arcade-speed]').select_option('classic')
            page.locator('[data-arcade-special]').uncheck()
            expect(page.locator('[data-tetris-preset="challenge"]')).to_have_attribute('aria-pressed','false')
            page.locator('[data-arcade-cols]').select_option('12')
            page.locator('[data-arcade-rows]').select_option('24')
            expect(page.locator('[data-grid-preview-size]')).to_have_text('12 × 24')
            expect(page.locator('[data-arcade-grid-preview]')).to_have_attribute('aria-label','Aperçu du plateau 12 colonnes par 24 lignes, appliqué à la prochaine partie')
            saved=page.evaluate("JSON.parse(localStorage.getItem('astralis:arcade:tetris-settings:v1'))")
            assert saved['cols']==12 and saved['rows']==24, saved
            page.locator('.arcade-settings>summary').click()
            page.locator('[data-arcade-restart]').click()
            state=page.evaluate("()=>({size:[document.querySelector('.arcade-board').width,document.querySelector('.arcade-board').height],status:document.querySelector('[data-arcade-status]').textContent,settings:JSON.parse(localStorage.getItem('astralis:arcade:tetris-settings:v1'))})")
            assert state['size']==[360,720], f"état après redémarrage : {state}; erreurs : {errors}"
            assert not errors, errors
            page.evaluate("""()=>{const buttons=Array.from({length:16},()=>({pressed:false,value:0}));window.__fakePadButtons=buttons;Object.defineProperty(navigator,'getGamepads',{configurable:true,value:()=>[{connected:true,index:0,id:'Manette de test',mapping:'standard',axes:[0,0],buttons}]});window.dispatchEvent(new Event('gamepadconnected'))}""")
            expect(page.locator('[data-gamepad-connection]')).to_have_text('Connectée')
            page.evaluate("window.__fakePadButtons[0].pressed=true")
            expect(page.locator('[data-gamepad-last-input]')).to_have_text('Dernière commande : Tourner')
            page.locator('[data-arcade-mode="lander"]').click()
            lander_pause=page.locator('[data-lander-pause]')
            expect(lander_pause).to_be_visible()
            expect(lander_pause).to_have_attribute('aria-pressed','false')
            lander_pause.click()
            expect(lander_pause).to_have_attribute('aria-pressed','true')
            expect(page.locator('[data-lander-status]')).to_contain_text('trajectoire est conservée')
            fuel_while_paused=page.locator('[data-lander-fuel]').inner_text()
            page.locator('[data-lander-canvas]').focus()
            page.keyboard.press('Space')
            page.wait_for_timeout(180)
            expect(page.locator('[data-lander-fuel]')).to_have_text(fuel_while_paused)
            page.keyboard.press('p')
            expect(lander_pause).to_have_attribute('aria-pressed','false')
            page.keyboard.press('p')
            expect(lander_pause).to_have_attribute('aria-pressed','true')
            page.locator('[data-lander-start]').click()
            expect(lander_pause).to_have_attribute('aria-pressed','false')
            expect(page.locator('[data-lander-status]')).to_contain_text('Vol engagé')
            page.set_viewport_size({'width':390,'height':844})
            assert page.locator('.arcade-contract-list').evaluate('(el)=>[...el.querySelectorAll(".arcade-contract-card")].every(card=>card.scrollWidth<=card.clientWidth+1)')
            page.evaluate('window.cleanup()')
            page.wait_for_timeout(110)
            expect(page.locator('[data-gamepad-last-input]')).to_have_text('Dernière commande : Tourner')
            browser.close()
        print('OK : les contrats ouvrent le bon mode, leur affichage téléphone tient dans l’écran et le plateau 12×24 conserve ses réglages.')
    finally:
        server.shutdown();server.server_close()


if __name__=='__main__':main()
