import assert from 'node:assert/strict';
import { teamKeys,setTeamSlot,chargeTeam,activateTeamBurst,teamBonuses } from '../src/express-team.js';
import { castPower,adventure } from '../src/express-adventure-engine.js';
const s={world:'gi',place:'mondstadt',characters:{active:'amber',owned:['amber','kaeya','lisa','barbara','ronova'],levels:{}},prestiges:0,combo:0};
const amber={id:10000021,name:'Amber',elementText:'Pyro'},lisa={name:'Lisa',elementText:'Électro'};
assert.deepEqual(teamKeys(s),['amber','kaeya','lisa','barbara']);
assert.equal(setTeamSlot(s,5,'ronova'),false);
assert.equal(setTeamSlot(s,1,'not-owned'),false);
assert.ok(setTeamSlot(s,1,'lisa'));
assert.deepEqual(teamKeys(s),['amber','lisa','kaeya','barbara']);
for(let i=0;i<25;i++)chargeTeam(s);
for(const key of teamKeys(s))assert.equal(s.clicker.energy['gi:'+key],100);
const base=adventure(s).hp;
const first=activateTeamBurst(s,'amber',amber,1000);assert.ok(first);
assert.equal(activateTeamBurst(s,'amber',amber,1001),null,'A second click must not award a second burst');
assert.ok(first);
const second=activateTeamBurst(s,'lisa',lisa,1002);assert.ok(second);
assert.ok(second);
assert.equal(teamBonuses(s,22000).entries.length,0);
assert.equal(adventure(s).hp,base,'Legacy percentage effects do not fabricate combat hits');
setTeamSlot(s,1,'ronova');assert.equal(teamBonuses(s,1004).entries.length,1,'Removing a member removes their support');
const giTeam=[...teamKeys(s)];s.world='hsr';s.characters={active:'march7th',owned:['march7th','danheng','himeko','asta'],levels:{}};
assert.deepEqual(teamKeys(s),['march7th','danheng','himeko','asta']);assert.equal(teamBonuses(s,1004).entries.length,0);
s.world='gi';s.characters={active:'amber',owned:['amber','kaeya','lisa','barbara','ronova'],levels:{}};
assert.deepEqual(teamKeys(s),giTeam);
const restored=JSON.parse(JSON.stringify(s));assert.deepEqual(teamKeys(restored),giTeam);
assert.ok(setTeamSlot(s,0,''));assert.equal(teamKeys(s)[0],null);assert.ok(teamKeys(s).includes(s.characters.active));
console.log('PASS: legacy save migration, four unique slots, swapping, ownership, legacy energy, double activation, expiry, member removal, world isolation and save restoration. Combat mechanics are verified by verify-express-adventure.mjs.');
